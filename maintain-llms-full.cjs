#!/usr/bin/env node
// Builds llms-full.txt from the Markdown summaries so the three never drift apart.
// Usage: node maintain-llms-full.cjs           (rewrite llms-full.txt)
//        node maintain-llms-full.cjs --check   (exit 1 when llms-full.txt is stale)
const fs = require('node:fs');
const path = require('node:path');

const origin = 'https://bitcoinfriesland.com';
const languages = [
  ['nl', 'Dutch'],
  ['en', 'English'],
  ['fy', 'Frisian'],
];
const pages = ['index', 'meetings', 'map', 'support', 'about', 'consumers', 'business'];

function buildLlmsFull(root = __dirname) {
  const parts = [
    '# Bitcoin Friesland: full text of core pages',
    '',
    '> Bitcoin Friesland (Frysk: Bitcoin Fryslân) is a volunteer community for Bitcoin education, adoption and meetups in the Dutch province of Friesland. This file joins the Markdown summaries of the core pages in Dutch, English and Frisian. The visible HTML pages are the primary source and win when they differ. Nothing here is financial advice.',
    '',
    'Generated by `node maintain-llms-full.cjs` from the `*.html.md` files. Edit those files, not this one.',
  ];
  for (const [language, label] of languages) {
    for (const page of pages) {
      const file = path.join(root, language, `${page}.html.md`);
      if (!fs.existsSync(file)) continue;
      const url = page === 'index' ? `${origin}/${language}/` : `${origin}/${language}/${page}`;
      const body = fs.readFileSync(file, 'utf8').trim().replace(/^(#+) /gm, '#$1 ');
      parts.push('', '---', '', `Language: ${label}. Source: ${url}`, '', body);
    }
  }
  return `${parts.join('\n')}\n`;
}

if (require.main === module) {
  const target = path.join(__dirname, 'llms-full.txt');
  const expected = buildLlmsFull();
  if (process.argv.includes('--check')) {
    const current = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : '';
    if (current !== expected) {
      console.error('llms-full.txt is out of date. Run: node maintain-llms-full.cjs');
      process.exit(1);
    }
    console.log('llms-full.txt is up to date.');
  } else {
    fs.writeFileSync(target, expected);
    console.log(`Wrote llms-full.txt (${expected.length} characters).`);
  }
}

module.exports = { buildLlmsFull };
