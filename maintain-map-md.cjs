#!/usr/bin/env node
// Keeps the business list in nl|en|fy/map.html.md equal to the table on the map pages,
// so AI assistants that read the Markdown summary can answer "where can I pay in Sneek?".
// Usage: node maintain-map-md.cjs           (rewrite the lists)
//        node maintain-map-md.cjs --check   (exit 1 when a list is stale)
const fs = require('node:fs');
const path = require('node:path');

const START = '<!-- businesses:start (generated by maintain-map-md.cjs; edit the table in map.html instead) -->';
const END = '<!-- businesses:end -->';
const text = {
  nl: { title: 'Bedrijven op de Bitcoin Kaart', intro: (n, t) => `${n} bedrijven in ${t} plaatsen.`, both: 'on-chain en Lightning', ln: 'alleen Lightning', chain: 'alleen on-chain', none: 'betaalmethode onbekend' },
  en: { title: 'Businesses on the Bitcoin map', intro: (n, t) => `${n} businesses in ${t} towns.`, both: 'on-chain and Lightning', ln: 'Lightning only', chain: 'on-chain only', none: 'payment method unknown' },
  fy: { title: 'Bedriuwen op de Bitcoinkaart', intro: (n, t) => `${n} bedriuwen yn ${t} plakken.`, both: 'on-chain en Lightning', ln: 'allinnich Lightning', chain: 'allinnich on-chain', none: 'betelmetoade ûnbekend' },
};

function clean(html) {
  return html.replace(/<svg[\s\S]*?<\/svg>/g, '').replace(/<[^>]+>/g, '').replace(/&amp;/g, '&').replace(/&#39;|&apos;/g, "'").replace(/&quot;/g, '"').replace(/\s+/g, ' ').trim();
}

function readBusinesses(html) {
  const table = html.slice(html.indexOf('id="businessTable"'));
  const body = table.slice(0, table.indexOf('</table>'));
  const caption = clean((body.match(/<caption[^>]*>([\s\S]*?)<\/caption>/) || [])[1] || '');
  const businesses = [];
  for (const row of body.matchAll(/<tr\b[^>]*>([\s\S]*?)<\/tr>/g)) {
    const cells = [...row[1].matchAll(/<td\b[^>]*>([\s\S]*?)<\/td>/g)].map((cell) => cell[1]);
    if (cells.length < 7) continue;
    const yes = (cell) => cell.includes('text-green-500');
    businesses.push({ name: clean(cells[0]), type: clean(cells[1]), address: clean(cells[2]), town: clean(cells[3]), chain: yes(cells[5]), lightning: yes(cells[6]) });
  }
  return { caption, businesses };
}

function buildSection(root, language) {
  const labels = text[language];
  const { caption, businesses } = readBusinesses(fs.readFileSync(path.join(root, language, 'map.html'), 'utf8'));
  const towns = new Map();
  for (const business of businesses) {
    if (!towns.has(business.town)) towns.set(business.town, []);
    towns.get(business.town).push(business);
  }
  const order = [...towns.keys()].sort((a, b) => towns.get(b).length - towns.get(a).length || a.localeCompare(b));
  const lines = [START, '', `## ${labels.title}`, '', `${labels.intro(businesses.length, towns.size)}${caption ? ` ${caption}.` : ''}`];
  for (const town of order) {
    lines.push('', `### ${town} (${towns.get(town).length})`, '');
    for (const b of towns.get(town)) {
      const pay = b.chain && b.lightning ? labels.both : b.lightning ? labels.ln : b.chain ? labels.chain : labels.none;
      lines.push(`- ${b.name}: ${b.type}, ${b.address}. Bitcoin: ${pay}.`);
    }
  }
  lines.push('', END);
  return lines.join('\n');
}

// Returns the Markdown file content with a fresh business section (appended when missing).
function withSection(root, language) {
  const file = path.join(root, language, 'map.html.md');
  const current = fs.readFileSync(file, 'utf8');
  const section = buildSection(root, language);
  const start = current.indexOf(START);
  const end = current.indexOf(END);
  if (start >= 0 && end > start) return current.slice(0, start) + section + current.slice(end + END.length);
  return `${current.trimEnd()}\n\n${section}\n`;
}

function staleMapMarkdown(root = __dirname) {
  return Object.keys(text).filter((language) => fs.readFileSync(path.join(root, language, 'map.html.md'), 'utf8') !== withSection(root, language));
}

if (require.main === module) {
  const stale = staleMapMarkdown();
  if (process.argv.includes('--check')) {
    if (stale.length) {
      console.error(`map.html.md business list is out of date for: ${stale.join(', ')} (run node maintain-map-md.cjs)`);
      process.exit(1);
    }
    console.log('map.html.md business lists are up to date.');
  } else {
    for (const language of stale) fs.writeFileSync(path.join(__dirname, language, 'map.html.md'), withSection(__dirname, language));
    console.log(stale.length ? `Updated: ${stale.join(', ')}` : 'map.html.md business lists were already up to date.');
  }
}

module.exports = { staleMapMarkdown, buildSection };
